/* Reporting / consumption views over the Data Vault layer. */

IF OBJECT_ID('dv.V_FACTOR_PANEL', 'V') IS NOT NULL DROP VIEW dv.V_FACTOR_PANEL;
GO
CREATE VIEW dv.V_FACTOR_PANEL AS
SELECT
    hf.FACTOR_KEY,
    hr.REGION_KEY,
    hp.PERIOD_KEY,
    hp.PERIOD_YEAR,
    so.OBS_VALUE,
    so.QUALITY_FLAG,
    hd.DATASET_KEY
FROM dv.LINK_OBSERVATION lo
JOIN dv.HUB_FACTOR  hf ON hf.HK_FACTOR  = lo.HK_FACTOR
JOIN dv.HUB_REGION  hr ON hr.HK_REGION  = lo.HK_REGION
JOIN dv.HUB_PERIOD  hp ON hp.HK_PERIOD  = lo.HK_PERIOD
JOIN dv.HUB_DATASET hd ON hd.HK_DATASET = lo.HK_DATASET
CROSS APPLY (
    SELECT TOP 1 s.OBS_VALUE, s.QUALITY_FLAG
    FROM dv.SAT_OBSERVATION s
    WHERE s.HK_OBSERVATION = lo.HK_OBSERVATION
    ORDER BY s.LOAD_DTS DESC
) so;
GO

IF OBJECT_ID('dv.V_FACTOR_META', 'V') IS NOT NULL DROP VIEW dv.V_FACTOR_META;
GO
CREATE VIEW dv.V_FACTOR_META AS
SELECT
    hf.FACTOR_KEY,
    sf.FACTOR_NAME,
    sf.CATEGORY,
    sf.DEFINITION,
    sf.EXPECTED_SIGN,
    sf.UNIT,
    sf.CITATION,
    sf.EVIDENCE,
    sf.IS_ACTIVE
FROM dv.HUB_FACTOR hf
CROSS APPLY (
    SELECT TOP 1 s.*
    FROM dv.SAT_FACTOR s
    WHERE s.HK_FACTOR = hf.HK_FACTOR
    ORDER BY s.LOAD_DTS DESC
) sf;
GO

IF OBJECT_ID('dv.V_FACTOR_RELATIONS', 'V') IS NOT NULL DROP VIEW dv.V_FACTOR_RELATIONS;
GO
CREATE VIEW dv.V_FACTOR_RELATIONS AS
SELECT
    hf1.FACTOR_KEY AS FACTOR_FROM,
    hf2.FACTOR_KEY AS FACTOR_TO,
    r.RELATION_TYPE,
    r.CONFIDENCE,
    r.PROVENANCE
FROM dv.LINK_FACTOR_RELATION r
JOIN dv.HUB_FACTOR hf1 ON hf1.HK_FACTOR = r.HK_FACTOR_FROM
JOIN dv.HUB_FACTOR hf2 ON hf2.HK_FACTOR = r.HK_FACTOR_TO;
GO

IF OBJECT_ID('dv.V_FACTOR_EMBEDDINGS', 'V') IS NOT NULL DROP VIEW dv.V_FACTOR_EMBEDDINGS;
GO
CREATE VIEW dv.V_FACTOR_EMBEDDINGS AS
SELECT
    hf.FACTOR_KEY,
    e.MODEL_VERSION,
    e.EMBED_DIM,
    e.EMBEDDING,
    e.LOAD_DTS
FROM dv.HUB_FACTOR hf
CROSS APPLY (
    SELECT TOP 1 s.MODEL_VERSION, s.EMBED_DIM, s.EMBEDDING, s.LOAD_DTS
    FROM dv.SAT_FACTOR_EMBEDDING s
    WHERE s.HK_FACTOR = hf.HK_FACTOR
    ORDER BY s.LOAD_DTS DESC
) e;
GO
