/* ==========================================================================
   Data Vault 2.0 schema for the NSW crime causal project  (MSSQL)
   Conventions:
     - Hub      : deterministic hash of the business key, insert-only
     - Link     : relationship between hubs, insert-only
     - Satellite: descriptive attributes, versioned by LOAD_DTS + HASHDIFF
   All objects live in schema "dv".
   ========================================================================== */

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'dv')
    EXEC ('CREATE SCHEMA dv');

/* ---------------------------------- Hubs ---------------------------------- */

IF OBJECT_ID('dv.HUB_FACTOR', 'U') IS NULL
CREATE TABLE dv.HUB_FACTOR (
    HK_FACTOR    CHAR(32)      NOT NULL CONSTRAINT PK_HUB_FACTOR PRIMARY KEY,
    FACTOR_KEY   VARCHAR(64)   NOT NULL CONSTRAINT UQ_HUB_FACTOR_KEY UNIQUE,
    LOAD_DTS     DATETIME2(3)  NOT NULL,
    LOAD_SRC     NVARCHAR(200) NOT NULL
);

IF OBJECT_ID('dv.HUB_REGION', 'U') IS NULL
CREATE TABLE dv.HUB_REGION (
    HK_REGION    CHAR(32)      NOT NULL CONSTRAINT PK_HUB_REGION PRIMARY KEY,
    REGION_KEY   VARCHAR(64)   NOT NULL CONSTRAINT UQ_HUB_REGION_KEY UNIQUE,
    LOAD_DTS     DATETIME2(3)  NOT NULL,
    LOAD_SRC     NVARCHAR(200) NOT NULL
);

IF OBJECT_ID('dv.HUB_PERIOD', 'U') IS NULL
CREATE TABLE dv.HUB_PERIOD (
    HK_PERIOD    CHAR(32)      NOT NULL CONSTRAINT PK_HUB_PERIOD PRIMARY KEY,
    PERIOD_KEY   VARCHAR(32)   NOT NULL CONSTRAINT UQ_HUB_PERIOD_KEY UNIQUE,
    PERIOD_YEAR  SMALLINT      NULL,
    PERIOD_TYPE  VARCHAR(16)   NULL,           -- YEAR | QUARTER | MONTH
    LOAD_DTS     DATETIME2(3)  NOT NULL,
    LOAD_SRC     NVARCHAR(200) NOT NULL
);

IF OBJECT_ID('dv.HUB_DATASET', 'U') IS NULL
CREATE TABLE dv.HUB_DATASET (
    HK_DATASET   CHAR(32)       NOT NULL CONSTRAINT PK_HUB_DATASET PRIMARY KEY,
    DATASET_KEY  NVARCHAR(128)  NOT NULL CONSTRAINT UQ_HUB_DATASET_KEY UNIQUE,
    LOAD_DTS     DATETIME2(3)   NOT NULL,
    LOAD_SRC     NVARCHAR(200)  NOT NULL
);

/* ---------------------------------- Links --------------------------------- */

/* One observation = one factor, measured for one region, in one period,
   sourced from one dataset. Raw numeric values live in SAT_OBSERVATION. */
IF OBJECT_ID('dv.LINK_OBSERVATION', 'U') IS NULL
CREATE TABLE dv.LINK_OBSERVATION (
    HK_OBSERVATION CHAR(32)      NOT NULL CONSTRAINT PK_LINK_OBSERVATION PRIMARY KEY,
    HK_FACTOR      CHAR(32)      NOT NULL CONSTRAINT FK_LINK_OBS_FACTOR REFERENCES dv.HUB_FACTOR(HK_FACTOR),
    HK_REGION      CHAR(32)      NOT NULL CONSTRAINT FK_LINK_OBS_REGION REFERENCES dv.HUB_REGION(HK_REGION),
    HK_PERIOD      CHAR(32)      NOT NULL CONSTRAINT FK_LINK_OBS_PERIOD REFERENCES dv.HUB_PERIOD(HK_PERIOD),
    HK_DATASET     CHAR(32)      NOT NULL CONSTRAINT FK_LINK_OBS_DATASET REFERENCES dv.HUB_DATASET(HK_DATASET),
    LOAD_DTS       DATETIME2(3)  NOT NULL,
    LOAD_SRC       NVARCHAR(200) NOT NULL
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_LINK_OBS_FACTOR')
CREATE INDEX IX_LINK_OBS_FACTOR ON dv.LINK_OBSERVATION (HK_FACTOR) INCLUDE (HK_REGION, HK_PERIOD);

/* Factor-to-factor relationships (LLM priors + empirical correlation edges).
   This is the graph the GNN performs message passing over. */
IF OBJECT_ID('dv.LINK_FACTOR_RELATION', 'U') IS NULL
CREATE TABLE dv.LINK_FACTOR_RELATION (
    HK_RELATION     CHAR(32)      NOT NULL CONSTRAINT PK_LINK_FACTOR_REL PRIMARY KEY,
    HK_FACTOR_FROM  CHAR(32)      NOT NULL CONSTRAINT FK_REL_FROM REFERENCES dv.HUB_FACTOR(HK_FACTOR),
    HK_FACTOR_TO    CHAR(32)      NOT NULL CONSTRAINT FK_REL_TO   REFERENCES dv.HUB_FACTOR(HK_FACTOR),
    RELATION_TYPE   VARCHAR(32)   NOT NULL,    -- causes | correlates | proxy_of
    CONFIDENCE      FLOAT         NULL,
    PROVENANCE      VARCHAR(32)   NOT NULL,    -- llm | correlation | manual
    LOAD_DTS        DATETIME2(3)  NOT NULL,
    LOAD_SRC        NVARCHAR(200) NOT NULL
);

/* -------------------------------- Satellites ------------------------------- */

IF OBJECT_ID('dv.SAT_FACTOR', 'U') IS NULL
CREATE TABLE dv.SAT_FACTOR (
    HK_FACTOR     CHAR(32)       NOT NULL CONSTRAINT FK_SAT_FACTOR REFERENCES dv.HUB_FACTOR(HK_FACTOR),
    LOAD_DTS      DATETIME2(3)   NOT NULL,
    HASHDIFF      CHAR(32)       NOT NULL,
    LOAD_SRC      NVARCHAR(200)  NOT NULL,
    FACTOR_NAME   NVARCHAR(200)  NULL,
    CATEGORY      VARCHAR(64)    NULL,
    DEFINITION    NVARCHAR(MAX)  NULL,
    EXPECTED_SIGN VARCHAR(8)     NULL,
    UNIT          NVARCHAR(64)   NULL,
    CITATION      NVARCHAR(MAX)  NULL,
    EVIDENCE      VARCHAR(32)    NULL,
    IS_ACTIVE     BIT            NOT NULL CONSTRAINT DF_SAT_FACTOR_ACTIVE DEFAULT (1),
    CONSTRAINT PK_SAT_FACTOR PRIMARY KEY (HK_FACTOR, LOAD_DTS)
);

IF OBJECT_ID('dv.SAT_OBSERVATION', 'U') IS NULL
CREATE TABLE dv.SAT_OBSERVATION (
    HK_OBSERVATION CHAR(32)      NOT NULL CONSTRAINT FK_SAT_OBS REFERENCES dv.LINK_OBSERVATION(HK_OBSERVATION),
    LOAD_DTS       DATETIME2(3)  NOT NULL,
    HASHDIFF       CHAR(32)      NOT NULL,
    LOAD_SRC       NVARCHAR(200) NOT NULL,
    OBS_VALUE      FLOAT         NULL,
    OBS_TEXT       NVARCHAR(255) NULL,
    QUALITY_FLAG   VARCHAR(32)   NULL,
    CONSTRAINT PK_SAT_OBSERVATION PRIMARY KEY (HK_OBSERVATION, LOAD_DTS)
);

IF OBJECT_ID('dv.SAT_REGION', 'U') IS NULL
CREATE TABLE dv.SAT_REGION (
    HK_REGION   CHAR(32)      NOT NULL CONSTRAINT FK_SAT_REGION REFERENCES dv.HUB_REGION(HK_REGION),
    LOAD_DTS    DATETIME2(3)  NOT NULL,
    HASHDIFF    CHAR(32)      NOT NULL,
    LOAD_SRC    NVARCHAR(200) NOT NULL,
    REGION_NAME NVARCHAR(200) NULL,
    REGION_TYPE VARCHAR(32)   NULL,           -- SA2 | LGA | POSTCODE | SEIFAP
    POPULATION  FLOAT         NULL,
    CONSTRAINT PK_SAT_REGION PRIMARY KEY (HK_REGION, LOAD_DTS)
);

/* GNN message-passing embeddings, one JSON vector row per version change. */
IF OBJECT_ID('dv.SAT_FACTOR_EMBEDDING', 'U') IS NULL
CREATE TABLE dv.SAT_FACTOR_EMBEDDING (
    HK_FACTOR     CHAR(32)      NOT NULL CONSTRAINT FK_SAT_EMB REFERENCES dv.HUB_FACTOR(HK_FACTOR),
    LOAD_DTS      DATETIME2(3)  NOT NULL,
    HASHDIFF      CHAR(32)      NOT NULL,
    LOAD_SRC      NVARCHAR(200) NOT NULL,
    MODEL_VERSION VARCHAR(32)   NOT NULL,
    EMBED_DIM     INT           NOT NULL,
    EMBEDDING     NVARCHAR(MAX) NOT NULL,     -- JSON array of floats
    CONSTRAINT PK_SAT_FACTOR_EMBEDDING PRIMARY KEY (HK_FACTOR, LOAD_DTS)
);
